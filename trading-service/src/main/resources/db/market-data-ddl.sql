-- ============================================================
-- 시세 데이터 (stocks / daily_candles / price_candles) DDL
--
-- ddl-auto: validate 사용 중이라 Hibernate가 스키마를 만들어주지 않는다.
-- 로컬에서 앱을 처음 띄우기 전에 psql / IntelliJ DB 콘솔에서 이 파일을 직접 실행해야 한다.
-- application-local.yml의 currentSchema=trading_service와 맞춰 스키마를 명시한다.
-- ============================================================

CREATE SCHEMA IF NOT EXISTS trading_service;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ----------------------------------------
-- 종목
-- ----------------------------------------
CREATE TABLE IF NOT EXISTS trading_service.p_stocks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol      VARCHAR(20)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    market      VARCHAR(20)  NOT NULL,
    currency    VARCHAR(3)   NOT NULL,
    is_active   BOOLEAN      NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ,
    CONSTRAINT uk_stocks_symbol UNIQUE (symbol)
);

-- ----------------------------------------
-- 일봉 (20일 최고가 등 진단 지표 계산용, 1년치)
-- ----------------------------------------
CREATE TABLE IF NOT EXISTS trading_service.p_daily_candles (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_id          BIGINT        NOT NULL REFERENCES trading_service.p_stocks (id),
    trade_date        DATE          NOT NULL,
    open_price        NUMERIC(19,4) NOT NULL,
    high_price        NUMERIC(19,4) NOT NULL,
    low_price         NUMERIC(19,4) NOT NULL,
    close_price       NUMERIC(19,4) NOT NULL,
    volume            BIGINT        NOT NULL,
    recent_20d_high   NUMERIC(19,4),
    recent_20d_low    NUMERIC(19,4),
    recent_5d_return  NUMERIC(7,2),
    created_at        TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uk_daily_candle UNIQUE (stock_id, trade_date)
);

CREATE INDEX IF NOT EXISTS idx_daily_candle_stock ON trading_service.p_daily_candles (stock_id);

-- ----------------------------------------
-- 1분봉 (가상 시계 리플레이 원본, seq는 전 종목 공통 시간축)
-- ----------------------------------------
CREATE TABLE IF NOT EXISTS trading_service.p_price_candles (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_id          BIGINT        NOT NULL REFERENCES trading_service.p_stocks (id),
    seq               BIGINT        NOT NULL,
    market_time       TIMESTAMPTZ   NOT NULL,
    open_price        NUMERIC(19,4) NOT NULL,
    high_price        NUMERIC(19,4) NOT NULL,
    low_price         NUMERIC(19,4) NOT NULL,
    close_price       NUMERIC(19,4) NOT NULL,
    volume            BIGINT        NOT NULL,
    recent_20d_high   NUMERIC(19,4),
    recent_20d_low    NUMERIC(19,4),
    recent_5d_return  NUMERIC(7,2),
    created_at        TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uk_price_candle UNIQUE (stock_id, seq)
);


-- ----------------------------------------
-- orders(임시 — Orders 도메인 소유자 확정 전까지 로컬 기동용 스텁)
-- BaseEntity 감사 컬럼 포함해야 ddl-auto: validate 통과함
-- ----------------------------------------
CREATE TABLE IF NOT EXISTS trading_service.p_orders (
    id          UUID PRIMARY KEY,
    created_at  TIMESTAMPTZ,
    created_by  UUID,
    updated_at  TIMESTAMPTZ,
    updated_by  UUID,
    deleted_at  TIMESTAMPTZ,
    deleted_by  UUID
);

-- 리플레이 스케줄러가 "현재 seq 이하만" 조회할 때 사용 (candles P1 API도 동일)
CREATE INDEX IF NOT EXISTS idx_price_candle_seq ON trading_service.p_price_candles (seq);
ALTER TABLE trading_service.p_orders
    ALTER COLUMN created_at TYPE TIMESTAMPTZ USING created_at AT TIME ZONE 'UTC',
    ALTER COLUMN updated_at TYPE TIMESTAMPTZ USING updated_at AT TIME ZONE 'UTC',
    ALTER COLUMN deleted_at TYPE TIMESTAMPTZ USING deleted_at AT TIME ZONE 'UTC';

-- ----------------------------------------
-- 시계
-- ----------------------------------------
CREATE TABLE IF NOT EXISTS trading_service.p_market_clock (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anchor_seq      BIGINT          NOT NULL,
    anchor_at       TIMESTAMPTZ     NOT NULL,
    anchor_market_time   TIMESTAMPTZ  NOT NULL,
    start_seq       BIGINT          NOT NULL,
    end_seq         BIGINT          NOT NULL,
    speed_factor    INT  NOT NULL,
    cache_refresh_interval_ms        INT NOT NULL,
    status          VARCHAR(20)     NOT NULL,
    updated_at      TIMESTAMPTZ     NOT NULL,
    updated_by      UUID
);

-- 이미 p_market_clock을 만들어둔 로컬 DB에서도 이 파일을 재실행하면 컬럼이 추가되도록
ALTER TABLE trading_service.p_market_clock ADD COLUMN IF NOT EXISTS updated_by UUID;

-- ----------------------------------------
-- 계좌
-- ----------------------------------------
CREATE TABLE IF NOT EXISTS trading_service.p_accounts (
    id              UUID            PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id         UUID            NOT NULL,
    cash_balance    NUMERIC(19, 4)  NOT NULL,
    initial_deposit NUMERIC(19, 4)  NOT NULL DEFAULT 100000.0000,
    currency        CHAR(3)         NOT NULL DEFAULT 'USD',
    created_at      TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by      UUID            NOT NULL,
    updated_at      TIMESTAMPTZ,
    updated_by      UUID,
    CONSTRAINT uk_accounts_user_id UNIQUE (user_id),
    CONSTRAINT ck_accounts_cash_balance_nonnegative CHECK (cash_balance >= 0)
);

-- ----------------------------------------
-- 현금 원장
-- ----------------------------------------
CREATE TABLE IF NOT EXISTS trading_service.p_cash_ledgers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      UUID            NOT NULL,
    execution_id    UUID,
    tx_type         VARCHAR(20)     NOT NULL,
    amount          NUMERIC(20, 4)  NOT NULL,
    balance_after   NUMERIC(20, 4)  NOT NULL,
    created_at      TIMESTAMPTZ     NOT NULL DEFAULT now(),
    CONSTRAINT fk_cash_ledgers_account_id
        FOREIGN KEY (account_id) REFERENCES trading_service.p_accounts (id),
    CONSTRAINT uk_cash_ledgers_execution_id UNIQUE (execution_id)
);

CREATE INDEX IF NOT EXISTS idx_cash_ledgers_account_id
    ON trading_service.p_cash_ledgers (account_id);
-- ----------------------------------------
--체결
-- ----------------------------------------
CREATE TABLE TABLE IF NOT EXISTS trading_service.p_executions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_id UUID NOT NULL UNIQUE,
    position_id UUID NOT NULL,
    user_id UUID NOT NULL,
    stock_id BIGINT NOT NULL,
    side VARCHAR(10) NOT NULL,
    executed_price NUMERIC(19, 4) NOT NULL,
    executed_quantity INTEGER NOT NULL,
    executed_amount NUMERIC(19, 4) GENERATED ALWAYS AS (executed_price * executed_quantity) STORED NOT NULL,
    avg_entry_price_at_execution NUMERIC(19, 4),
    realized_profit NUMERIC(19, 4),
    candle_seq BIGINT NOT NULL,
    market_time TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by UUID NOT NULL,
    updated_at TIMESTAMPTZ,
    updated_by UUID,
    deleted_at TIMESTAMPTZ,
    deleted_by UUID
);

    -- INDEX 생성
    CREATE INDEX idx_p_executions_order_id ON trading_service.p_executions(order_id);
    CREATE INDEX idx_p_executions_position_id ON trading_service.p_executions(position_id);
    CREATE INDEX idx_p_executions_user_id ON trading_service.p_executions(user_id);
    CREATE INDEX idx_p_executions_stock_id ON trading_service.p_executions(stock_id);